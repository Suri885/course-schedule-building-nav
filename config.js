// 下面把 OCR_ENABLED 打开并填好云环境后，即可走云端 OCR 自动识别。
//
// ===================== 开通「拍照自动识别」4 步 =====================
// 1) 微信开发者工具顶部点「☁ 云开发」→ 开通（选按量计费，有免费额度）→ 复制「环境 ID」。
//    把这个环境 ID 填到下面的 CLOUD_ENV。
// 2) 在微信开发者工具里，右键本项目 cloudfunctions/ocr 目录
//    →「上传并部署：云端安装依赖」（会自动装 wx-server-sdk 和腾讯云 OCR SDK）。
// 3) 准备腾讯云密钥：登录 console.cloud.tencent.com → 访问管理 → API 密钥管理，
//    新建密钥得到 SecretId / SecretKey。
//    再到云开发控制台 → 云函数 ocr → 配置 → 环境变量，添加：
//        TENCENT_SECRET_ID  = 你的 SecretId
//        TENCENT_SECRET_KEY = 你的 SecretKey
//    （密钥放环境变量，不要写进代码，更安全）
//    注意：腾讯云「文字识别 OCR」服务要单独开通（有免费额度），否则调用会报错。
// 4) 把下面 OCR_ENABLED 改为 true，重新编译小程序即可。
//    进导入页 →「智能统一导入」→ 上传课表照片 → 自动识别并生成可编辑预览。
// ====================================================================

