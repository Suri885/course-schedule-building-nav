// 工具：按 key 取板块
function getSection(key) {
  return SECTIONS.find(s => s.key === key) || null
}

// 工具：在全部板块中按任务 id 找任务及其所属板块
function findTask(taskId) {
  for (const s of SECTIONS) {
    const t = s.basic.concat(s.ext).find(x => x.id === taskId)
    if (t) return { section: s, task: t }
  }
  return null
}

module.exports = { SECTIONS, TOTAL_MAX, getSection, findTask }
